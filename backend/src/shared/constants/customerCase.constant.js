const getCustomerCasePriority = (category) => {
    if (category === CUSTOMER_CASE_CATEGORIES.SAFETY_CONCERN) {
        return CUSTOMER_CASE_PRIORITIES.CRITICAL;
    }

    if ([
        CUSTOMER_CASE_CATEGORIES.VEHICLE_DAMAGE,
        CUSTOMER_CASE_CATEGORIES.MISSING_PROPERTY,
    ].includes(category)) {
        return CUSTOMER_CASE_PRIORITIES.HIGH;
    }

    return CUSTOMER_CASE_PRIORITIES.NORMAL;
};

const getCustomerCasePriorityRank = (priority) => ({
    [CUSTOMER_CASE_PRIORITIES.NORMAL]: 1,
    [CUSTOMER_CASE_PRIORITIES.HIGH]: 2,
    [CUSTOMER_CASE_PRIORITIES.CRITICAL]: 3,
})[priority] || 1;

